"""Tests for sonyxm.protocol. No headphones needed.

Expected byte strings are written out by hand (or copied from Gadgetbridge's
own tests, see PROTOCOL.md §2), not generated by the code under test.
"""

import unittest

from sonyxm import protocol as p
from sonyxm.protocol import (
    Battery,
    ChargingStatus,
    ForbiddenCommandError,
    Frame,
    FrameError,
    FrameParser,
    MessageType,
    NcAsmMode,
    NcAsmState,
    PayloadError,
    ProtocolError,
)

CMD = MessageType.COMMAND_1
V2_MODES = [m for m in NcAsmMode if m is not NcAsmMode.WIND]  # wind noise reduction is V1 only


def h(text: str) -> bytes:
    return bytes.fromhex(text)


class ChecksumTest(unittest.TestCase):
    def test_sum(self):
        self.assertEqual(p.checksum(h("0c 00 00 00 00 02 00 00")), 0x0E)

    def test_wraps_to_low_byte(self):
        # From Gadgetbridge's getQuickAccess vector: 0x111 -> 0x11
        self.assertEqual(p.checksum(h("0c 00 00 00 00 02 f6 0d")), 0x11)

    def test_empty(self):
        self.assertEqual(p.checksum(b""), 0)


class EscapeTest(unittest.TestCase):
    def test_special_bytes(self):
        self.assertEqual(p.escape(h("3c")), h("3d 2c"))
        self.assertEqual(p.escape(h("3d")), h("3d 2d"))
        self.assertEqual(p.escape(h("3e")), h("3d 2e"))

    def test_other_bytes_untouched(self):
        data = bytes(b for b in range(256) if b not in (0x3C, 0x3D, 0x3E))
        self.assertEqual(p.escape(data), data)

    def test_round_trip_all_bytes(self):
        data = bytes(range(256)) * 2
        escaped = p.escape(data)
        self.assertNotIn(0x3C, escaped)
        self.assertNotIn(0x3E, escaped)
        self.assertEqual(p.unescape(escaped), data)

    def test_unescape(self):
        self.assertEqual(p.unescape(h("01 3d 2c 3d 2d 3d 2e 02")), h("01 3c 3d 3e 02"))

    def test_unescape_rejects_unknown_sequence(self):
        with self.assertRaises(FrameError):
            p.unescape(h("3d 41"))

    def test_unescape_rejects_trailing_escape(self):
        with self.assertRaises(FrameError):
            p.unescape(h("01 3d"))


class PackTest(unittest.TestCase):
    """The raw framing primitive, with payloads the whitelist would refuse."""

    def test_payload_byte_escaped(self):
        self.assertEqual(p._pack(0x0C, 0, h("3d")), h("3e 0c 00 00 00 00 01 3d 2d 4a 3c"))

    def test_checksum_byte_escaped(self):
        # 0c + 01 + 30 = 3d, so the checksum itself has to be escaped
        self.assertEqual(p._pack(0x0C, 0, h("30")), h("3e 0c 00 00 00 00 01 30 3d 2d 3c"))

    def test_length_is_four_bytes_big_endian(self):
        frame = p._pack(0x0C, 0, bytes(300))
        self.assertEqual(frame[1:7], h("0c 00 00 00 01 2c"))


class EncodeTest(unittest.TestCase):
    def test_init(self):
        self.assertEqual(
            p.encode_frame(Frame(CMD, 0, p.init_request()), p.V2),
            h("3e 0c 00 00 00 00 02 00 00 0e 3c"),
        )
        self.assertEqual(
            p.encode_frame(Frame(CMD, 1, p.init_request()), p.V2),
            h("3e 0c 01 00 00 00 02 00 00 0f 3c"),
        )

    def test_battery(self):
        self.assertEqual(p.battery_request(), h("22 00"))  # Gadgetbridge getBattery(SINGLE)
        self.assertEqual(
            p.encode_frame(Frame(CMD, 0, p.battery_request()), p.V2),
            h("3e 0c 00 00 00 00 02 22 00 30 3c"),
        )
        self.assertEqual(
            p.encode_frame(Frame(CMD, 1, p.battery_request()), p.V2),
            h("3e 0c 01 00 00 00 02 22 00 31 3c"),
        )

    def test_ncasm_get(self):
        self.assertEqual(
            p.encode_frame(Frame(CMD, 0, p.ncasm_request(0x15)), p.V2),
            h("3e 0c 00 00 00 00 02 66 15 89 3c"),
        )
        self.assertEqual(
            p.encode_frame(Frame(CMD, 1, p.ncasm_request(0x17)), p.V2),
            h("3e 0c 01 00 00 00 02 66 17 8c 3c"),
        )

    def test_ncasm_set_frames(self):
        nc = NcAsmState(NcAsmMode.NOISE_CANCELLING, False, 20)
        self.assertEqual(
            p.encode_frame(Frame(CMD, 0, p.ncasm_set(0x15, nc)), p.V2),
            h("3e 0c 00 00 00 00 07 68 15 01 01 00 00 14 a6 3c"),
        )
        ambient = NcAsmState(NcAsmMode.AMBIENT, False, 10)
        self.assertEqual(
            p.encode_frame(Frame(CMD, 0, p.ncasm_set(0x15, ambient)), p.V2),
            h("3e 0c 00 00 00 00 07 68 15 01 01 01 00 0a 9d 3c"),
        )

    def test_ack(self):
        self.assertEqual(p.encode_frame(Frame(MessageType.ACK, 1), p.V2), h("3e 01 01 00 00 00 00 02 3c"))
        self.assertEqual(p.encode_frame(Frame(MessageType.ACK, 0), p.V2), h("3e 01 00 00 00 00 00 01 3c"))


class NcAsmSetTest(unittest.TestCase):
    # Same layout as Gadgetbridge's (commented-out) 0x17 vectors in SonyProtocolImplV2Test
    VECTORS = [
        (NcAsmState(NcAsmMode.AMBIENT, False, 20), "68 17 01 01 01 00 14"),
        (NcAsmState(NcAsmMode.OFF, False, 20), "68 17 01 00 00 00 14"),
        (NcAsmState(NcAsmMode.AMBIENT, False, 10), "68 17 01 01 01 00 0a"),
        (NcAsmState(NcAsmMode.AMBIENT, True, 20), "68 17 01 01 01 01 14"),
        (NcAsmState(NcAsmMode.NOISE_CANCELLING, False, 20), "68 17 01 01 00 00 14"),
    ]

    def test_payloads(self):
        for state, expected in self.VECTORS:
            with self.subTest(state=state):
                self.assertEqual(p.ncasm_set(0x17, state), h(expected))

    def test_subtype_0x15(self):
        state = NcAsmState(NcAsmMode.AMBIENT, True, 7)
        self.assertEqual(p.ncasm_set(0x15, state), h("68 15 01 01 01 01 07"))

    def test_level_range(self):
        for level in (1, 20):
            p.ncasm_set(0x15, NcAsmState(NcAsmMode.AMBIENT, False, level))
        # The XM5 turns a written 0 into 1, so 0 is refused
        for level in (-1, 0, 21):
            with self.subTest(level=level), self.assertRaises(ValueError):
                p.ncasm_set(0x15, NcAsmState(NcAsmMode.AMBIENT, False, level))

    def test_bad_subtype(self):
        with self.assertRaises(ValueError):
            p.ncasm_set(0x16, NcAsmState(NcAsmMode.AMBIENT, False, 5))
        with self.assertRaises(ValueError):
            p.ncasm_request(0x03)


class DecodeTest(unittest.TestCase):
    def test_gadgetbridge_vectors(self):
        # Frames from Gadgetbridge's SonyProtocolImplV2Test (Message.fromBytes verifies checksums)
        vectors = [
            ("3e 0c 01 00 00 00 02 12 02 23 3c", Frame(0x0C, 1, h("12 02"))),
            ("3e 0c 00 00 00 00 02 f6 0d 11 3c", Frame(0x0C, 0, h("f6 0d"))),
            ("3e 0c 00 00 00 00 03 e9 01 00 f9 3c", Frame(0x0C, 0, h("e9 01 00"))),
            ("3e 0c 01 00 00 00 03 e9 01 01 fb 3c", Frame(0x0C, 1, h("e9 01 01"))),
            (
                "3e 0c 01 00 00 00 0a 59 00 00 06 0a 0a 0a 0a 0a 0a b2 3c",
                Frame(0x0C, 1, h("59 00 00 06 0a 0a 0a 0a 0a 0a")),
            ),
        ]
        for raw, expected in vectors:
            with self.subTest(raw=raw):
                self.assertEqual(p.decode_frame(h(raw)), expected)

    def test_ack(self):
        self.assertEqual(p.decode_frame(h("3e 01 01 00 00 00 00 02 3c")), Frame(MessageType.ACK, 1))

    def test_escaped_payload(self):
        # Battery at 60 % = 0x3c, so the level byte arrives escaped
        frame = p.decode_frame(h("3e 0c 00 00 00 00 04 23 00 3d 2c 00 6f 3c"))
        self.assertEqual(frame.payload, h("23 00 3c 00"))

    def test_escaped_checksum(self):
        frame = p.decode_frame(h("3e 0c 00 00 00 00 04 23 00 0a 00 3d 2d 3c"))
        self.assertEqual(frame.payload, h("23 00 0a 00"))

    def test_unknown_type_is_kept(self):
        raw = p._pack(0x42, 0, h("01"))
        self.assertEqual(p.decode_frame(raw), Frame(0x42, 0, h("01")))

    def test_bad_checksum(self):
        with self.assertRaisesRegex(FrameError, "checksum"):
            p.decode_frame(h("3e 0c 00 00 00 00 02 22 00 31 3c"))

    def test_length_mismatch(self):
        with self.assertRaisesRegex(FrameError, "length"):
            p.decode_frame(h("3e 0c 00 00 00 00 03 22 00 31 3c"))

    def test_too_short(self):
        with self.assertRaises(FrameError):
            p.decode_frame(h("3e 01 00 3c"))

    def test_missing_markers(self):
        for raw in ("0c 00 00 00 00 02 22 00 30 3c", "3e 0c 00 00 00 00 02 22 00 30", ""):
            with self.subTest(raw=raw), self.assertRaises(FrameError):
                p.decode_frame(h(raw))

    def test_unescaped_marker_inside(self):
        with self.assertRaises(FrameError):
            p.decode_frame(h("3e 0c 00 3e 00 00 02 22 00 30 3c"))

    def test_round_trip_every_allowed_frame(self):
        payloads = [p.init_request(), p.battery_request()]
        for subtype in p.NCASM_SUBTYPES:
            payloads.append(p.ncasm_request(subtype))
            for mode in V2_MODES:
                payloads.append(p.ncasm_set(subtype, NcAsmState(mode, True, 20)))
        for payload in payloads:
            for seq in (0, 1):
                frame = Frame(CMD, seq, payload)
                with self.subTest(frame=str(frame)):
                    self.assertEqual(p.decode_frame(p.encode_frame(frame, p.V2)), frame)


class FrameParserTest(unittest.TestCase):
    BATTERY = h("3e 0c 01 00 00 00 02 22 00 31 3c")
    ACK = h("3e 01 01 00 00 00 00 02 3c")

    def setUp(self):
        self.errors = []
        self.parser = FrameParser(on_error=lambda raw, err: self.errors.append((raw, err)))

    def test_two_frames_in_one_chunk(self):
        frames = self.parser.feed(self.ACK + self.BATTERY)
        self.assertEqual(frames, [Frame(MessageType.ACK, 1), Frame(CMD, 1, h("22 00"))])
        self.assertEqual(self.errors, [])

    def test_byte_by_byte(self):
        frames = []
        for b in self.BATTERY + self.ACK:
            frames += self.parser.feed(bytes((b,)))
        self.assertEqual(frames, [Frame(CMD, 1, h("22 00")), Frame(MessageType.ACK, 1)])
        self.assertEqual(self.errors, [])

    def test_split_inside_escape_sequence(self):
        raw = h("3e 0c 00 00 00 00 04 23 00 3d 2c 00 6f 3c")
        split = raw.index(0x3D) + 1
        self.assertEqual(self.parser.feed(raw[:split]), [])
        self.assertEqual(self.parser.feed(raw[split:]), [Frame(CMD, 0, h("23 00 3c 00"))])

    def test_garbage_before_header(self):
        frames = self.parser.feed(h("00 ff") + self.ACK)
        self.assertEqual(frames, [Frame(MessageType.ACK, 1)])
        self.assertEqual(self.errors[0][0], h("00 ff"))

    def test_bad_frame_does_not_block_next(self):
        bad = h("3e 0c 00 00 00 00 02 22 00 31 3c")  # wrong checksum
        frames = self.parser.feed(bad + self.ACK)
        self.assertEqual(frames, [Frame(MessageType.ACK, 1)])
        self.assertEqual(len(self.errors), 1)
        self.assertEqual(self.errors[0][0], bad)

    def test_truncated_frame_is_dropped(self):
        truncated = self.BATTERY[:5]
        frames = self.parser.feed(truncated + self.ACK)
        self.assertEqual(frames, [Frame(MessageType.ACK, 1)])
        self.assertEqual(self.errors[0][0], truncated)

    def test_waits_for_trailer(self):
        self.assertEqual(self.parser.feed(self.BATTERY[:-1]), [])
        self.assertEqual(self.parser.feed(self.BATTERY[-1:]), [Frame(CMD, 1, h("22 00"))])

    def test_runaway_frame_is_discarded(self):
        self.assertEqual(self.parser.feed(h("3e") + bytes(5000)), [])
        self.assertEqual(len(self.errors), 1)
        self.assertEqual(self.parser.feed(self.ACK), [Frame(MessageType.ACK, 1)])

    def test_without_error_callback(self):
        parser = FrameParser()
        self.assertEqual(parser.feed(h("00") + self.ACK), [Frame(MessageType.ACK, 1)])


