class WhitelistVersionsTest(unittest.TestCase):
    def assert_allowed(self, version, payloads):
        for payload in payloads:
            with self.subTest(version=version, payload=payload):
                p.check_allowed(Frame(CMD, 0, h(payload)), version)

    def assert_refused(self, version, payloads):
        for payload in payloads:
            with self.subTest(version=version, payload=payload), self.assertRaises(ForbiddenCommandError):
                p.encode_frame(Frame(CMD, 0, h(payload)), version)

    def test_before_the_handshake_only_init(self):
        self.assert_allowed(None, ["00 00"])
        self.assert_refused(None, ["22 00", "10 00", "66 17", "66 02", "56 00"])

    def test_v1(self):
        self.assert_allowed(p.V1, ["00 00", "10 00", "66 02", "56 01", "58 01 10 00", "68 02 11 02 02 01 00 00",
                                   "58 01 ff 06 0a 0a 0a 0a 0a 0a"])
        self.assert_refused(p.V1, [
            "22 00",  # V2's battery query is V1's power off
            "22 00 01",  # V1 power off (Gadgetbridge V1 powerOff)
            "98 01 02 01",  # V1 reboot
            "84 01 00 01",  # noise cancelling optimizer
            "f8 05 01 01",  # speak-to-chat / auto power off settings
            "66 17", "68 17 01 01 01 00 0a", "56 00", "58 00 10 00", "10 01",
            "58 01 a0 06 0a 0a 0a 0a 0a 0a",  # V1 bands go with preset ff
            "68 02 11 02 03 01 00 00",  # mode 3
            "68 02 01 02 02 01 00 00",  # V1 switches on with 11
            "68 02 11 00 02 01 00 00",  # setting type without wind
            "68 02 11 02 02 01 00 15",  # level 21
            "68 02 11 02 02 00 00 00",
        ])

    def test_v2_refuses_v1_commands(self):
        self.assert_refused(p.V2, ["10 00", "66 02", "56 01", "68 02 11 02 02 01 00 00",
                                   "58 01 ff 06 0a 0a 0a 0a 0a 0a", "58 01 10 00"])

    def test_v2_xm6(self):
        ten = " ".join(["06"] * 10)
        self.assert_allowed(p.V2, ["22 08", "66 19", "68 19 01 01 01 00 0a 00 00", "68 19 01 01 01 01 14 01 02",
                                   f"58 00 a0 0a {ten}", "58 00 30 00", "58 00 33 00"])
        self.assert_refused(p.V2, [
            "68 19 01 01 01 00 0a 00 03",  # unknown sensitivity
            "68 19 01 01 01 00 0a 02 00",
            "68 19 01 01 01 00 0a",  # too short for 0x19
            "68 17 01 01 01 00 0a 00 00",  # too long for 0x17
            "58 00 a0 0a " + " ".join(["06"] * 9) + " 0d",  # step +7
            "58 00 a0 0a " + " ".join(["06"] * 9),  # 9 values
            "58 00 31 0a " + ten,  # bands into a factory preset
            "22 01", "22 03", "22 08 00",
        ])


